import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
const game=fs.readFileSync(new URL('./game-v2.js',import.meta.url),'utf8');
const levels=fs.readFileSync(new URL('./levels.js',import.meta.url),'utf8');
const core=fs.readFileSync(new URL('./campaign-core.js',import.meta.url),'utf8');
const sw=fs.readFileSync(new URL('./sw.js',import.meta.url),'utf8');
const bomb=fs.readFileSync(new URL('./bomb-enemy.js',import.meta.url),'utf8');
const worlds=fs.readFileSync(new URL('./world-rules.js',import.meta.url),'utf8');
assert.match(html,/VERSIONE 2\.0\.5/); assert.match(html,/data-start-lives="3"/); assert.match(html,/data-start-lives="7"/);
for(const script of ['levels','campaign-core','game-v2','world-rules','spawn-patterns','spawn-tuning','bomb-enemy']) assert.match(html,new RegExp(`<script src="${script}\\.js"><\\/script>`));
assert.match(html,/data-action="inhale"/); assert.match(html,/Aspira: <kbd>C<\/kbd>/); assert.doesNotMatch(html,/<script src="game\.js"><\/script>/);
for(const world of ['LABORATORIO','CASA',"SOTT\\'ACQUA",'MARTE']) assert.ok(levels.includes(world));
for(const hazard of ['zombie-tube','sofa','plane','bottle','fish','boot','alien','spaceship','fridge']) assert.ok(levels.includes(hazard));
for(const token of ['createCampaignState()','VITE','gainLife','loseLife','bossType','ALIENO GIGANTE','MEGA PALAZZO','advanceLevel','hazardReachable','clampHazardSpeed','alienBossOffset']) assert.ok(game.includes(token));
assert.match(core,/MIN_LIVES = 3/); assert.match(core,/MAX_LIVES = 7/); assert.match(core,/configuredLives/);
assert.match(worlds,/bossAfterScore = Number\.POSITIVE_INFINITY/); assert.match(worlds,/boss-gateway/); assert.match(worlds,/fridgeWasShot/);
assert.match(bomb,/type: 'bomb'/); assert.match(bomb,/INHALE_RANGE = 250/); assert.match(bomb,/blastAfterIngestion/);
assert.match(sw,/lab8-v2\.0\.5/); assert.match(sw,/world-rules\.js/); assert.match(sw,/bomb-enemy\.js/);
console.log('LAB-8 2.0.5 runtime wiring: OK');
